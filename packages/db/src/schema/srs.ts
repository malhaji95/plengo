import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { flashcards } from './content.js';
import { srsRatingEnum, srsStateEnum } from './enums.js';
import { users } from './identity.js';

/*
 * Spaced repetition state and history (spec §13.7). Scheduling runs on the device; the server stores
 * what clients computed after validation (§13.6). `user_card_id` points at student cards, whose table
 * arrives with Phase 8 (the foreign key is added then).
 */

const exactlyOneCard = (table: string, t: { flashcardId: unknown; userCardId: unknown }) =>
  check(`${table}_card_ck`, sql`(${t.flashcardId} is null) <> (${t.userCardId} is null)`);

export const cardStates = pgTable(
  'card_states',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    flashcardId: uuid('flashcard_id').references(() => flashcards.id),
    userCardId: uuid('user_card_id'),
    state: srsStateEnum('state').notNull(),
    step: integer('step').notNull().default(0),
    dueAt: timestamp('due_at', { withTimezone: true }).notNull(),
    /** Whole days (the scheduler never produces fractions). */
    intervalDays: integer('interval_days').notNull().default(0),
    ease: doublePrecision('ease').notNull(),
    reps: integer('reps').notNull().default(0),
    lapses: integer('lapses').notNull().default(0),
    lastReviewedAt: timestamp('last_reviewed_at', { withTimezone: true }),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    exactlyOneCard('card_states', t),
    uniqueIndex('card_states_user_flashcard_uq').on(t.userId, t.flashcardId),
    uniqueIndex('card_states_user_user_card_uq').on(t.userId, t.userCardId),
    index('card_states_user_due_idx').on(t.userId, t.dueAt),
    index('card_states_user_updated_idx').on(t.userId, t.updatedAt),
  ],
);

export const reviewLogs = pgTable(
  'review_logs',
  {
    /** Generated by the client: the idempotency key for sync. */
    id: uuid('id').primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    flashcardId: uuid('flashcard_id').references(() => flashcards.id),
    userCardId: uuid('user_card_id'),
    rating: srsRatingEnum('rating').notNull(),
    stateBefore: jsonb('state_before').$type<Record<string, unknown>>().notNull(),
    stateAfter: jsonb('state_after').$type<Record<string, unknown>>().notNull(),
    reviewedAt: timestamp('reviewed_at', { withTimezone: true }).notNull(),
    durationMs: integer('duration_ms'),
    undone: boolean('undone').notNull().default(false),
    devicePlatform: text('device_platform'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    exactlyOneCard('review_logs', t),
    index('review_logs_user_reviewed_idx').on(t.userId, t.reviewedAt),
  ],
);
