#!/usr/bin/env node
/*
 * Builds web/privacy.html and web/terms.html from assets/legal/*.md, so the app, the web pages and
 * the store listings show one text. Cloudflare Pages serves them at /privacy and /terms.
 *
 *   node tool/legal_html.mjs          write the pages
 *   node tool/legal_html.mjs --check  fail when a page is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function render(markdown) {
  const out = [];
  let list = false;
  let title = '';
  for (const raw of markdown.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    const item = line.startsWith('- ');
    if (list && !item) {
      out.push('</ul>');
      list = false;
    }
    if (line.startsWith('## ')) out.push(`<h2>${escape(line.slice(3))}</h2>`);
    else if (line.startsWith('# ')) {
      title = line.slice(2);
      out.push(`<h1>${escape(title)}</h1>`);
    } else if (item) {
      if (!list) out.push('<ul>');
      list = true;
      out.push(`<li>${escape(line.slice(2))}</li>`);
    } else out.push(`<p>${escape(line)}</p>`);
  }
  if (list) out.push('</ul>');
  return `<!DOCTYPE html>
<!-- Generated by tool/legal_html.mjs from assets/legal; edit the Markdown, not this file. -->
<html lang="ar" dir="rtl">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(title)} — Plengo</title>
<style>
body { font-family: system-ui, sans-serif; line-height: 1.8; color: #1b1f1e; background: #F5FAF8; margin: 0; }
main { max-width: 720px; margin: 0 auto; padding: 24px 16px 48px; }
h1 { color: #00796B; } h2 { margin-top: 28px; }
@media (prefers-color-scheme: dark) { body { color: #e1e3e2; background: #101413; } h1 { color: #80CBC4; } }
</style>
</head>
<body>
<main>
${out.join('\n')}
</main>
</body>
</html>
`;
}

const check = process.argv.includes('--check');
let stale = false;
for (const name of ['privacy', 'terms']) {
  const html = render(readFileSync(`assets/legal/${name}.md`, 'utf8'));
  const target = `web/${name}.html`;
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {}
    if (current !== html) {
      console.error(`${target} is out of date: run node tool/legal_html.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(target, html);
    console.log(`wrote ${target}`);
  }
}
if (stale) process.exit(1);
